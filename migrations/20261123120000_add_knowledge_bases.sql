-- Knowledge bases: views onto collections of read-only connections, shared with users, teams, roles or everyone.

CREATE TABLE knowledge_bases (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 100),
    description TEXT CHECK (description IS NULL OR char_length(description) <= 2000),
    -- A connection cannot be deleted while knowledge bases point at it.
    connection_id UUID NOT NULL REFERENCES rag_connections(id) ON DELETE RESTRICT,
    -- Collection, vector, embedding model, field mapping and fixed filter (`ExternalView`).
    view JSONB NOT NULL,
    shared_with_everyone BOOLEAN NOT NULL DEFAULT FALSE,
    created_by UUID REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_knowledge_bases_connection ON knowledge_bases(connection_id);

CREATE TABLE knowledge_base_shares (
    knowledge_base_id UUID NOT NULL REFERENCES knowledge_bases(id) ON DELETE CASCADE,
    user_id UUID REFERENCES users(id) ON DELETE CASCADE,
    team_id UUID REFERENCES teams(id) ON DELETE CASCADE,
    role_id UUID REFERENCES roles(id) ON DELETE CASCADE,
    role TEXT NOT NULL DEFAULT 'viewer' CHECK (role IN ('viewer', 'editor')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (num_nonnulls(user_id, team_id, role_id) = 1),
    UNIQUE NULLS NOT DISTINCT (knowledge_base_id, user_id, team_id, role_id)
);

CREATE INDEX idx_knowledge_base_shares_user ON knowledge_base_shares(user_id) WHERE user_id IS NOT NULL;
CREATE INDEX idx_knowledge_base_shares_team ON knowledge_base_shares(team_id) WHERE team_id IS NOT NULL;
CREATE INDEX idx_knowledge_base_shares_role ON knowledge_base_shares(role_id) WHERE role_id IS NOT NULL;

