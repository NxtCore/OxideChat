CREATE TABLE IF NOT EXISTS budget_reset_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    assignment_id UUID REFERENCES budget_assignments(id) ON DELETE SET NULL,
    budget_id UUID REFERENCES budgets(id) ON DELETE SET NULL,
    team_id UUID REFERENCES teams(id) ON DELETE SET NULL,
    user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    kind budget_kind,
    reason TEXT,
    reset_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by UUID REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT budget_reset_events_scope_check CHECK (
        assignment_id IS NOT NULL OR
        budget_id IS NOT NULL OR
        team_id IS NOT NULL OR
        user_id IS NOT NULL
    )
);

CREATE INDEX IF NOT EXISTS idx_budget_reset_events_assignment ON budget_reset_events(assignment_id, reset_at);
CREATE INDEX IF NOT EXISTS idx_budget_reset_events_budget ON budget_reset_events(budget_id, reset_at);
CREATE INDEX IF NOT EXISTS idx_budget_reset_events_team ON budget_reset_events(team_id, reset_at);
CREATE INDEX IF NOT EXISTS idx_budget_reset_events_user ON budget_reset_events(user_id, reset_at);

