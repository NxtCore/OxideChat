-- Knowledge (RAG) setup: where vectors live and which models build and rerank them.

CREATE TABLE rag_connections (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL UNIQUE CHECK (char_length(btrim(name)) BETWEEN 1 AND 100),
    kind TEXT NOT NULL CHECK (kind IN ('pgvector', 'qdrant')),
    mode TEXT NOT NULL CHECK (mode IN ('managed', 'read_only')),
    -- NULL: the main database (managed pgvector only). Never holds a password.
    url TEXT,
    -- Encrypted Postgres password or Qdrant API key.
    secret TEXT,
    embedding_model_id UUID REFERENCES models(id) ON DELETE SET NULL,
    -- Requested from the model; NULL sends no dimensions and takes the model default.
    dimensions INTEGER CHECK (dimensions BETWEEN 1 AND 4000),
    -- What the test embedding returned: the size of every vector in this connection.
    vector_size INTEGER CHECK (vector_size BETWEEN 1 AND 4000),
    index_generation INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (mode = 'read_only' OR kind = 'pgvector'),
    CHECK (url IS NOT NULL OR (kind = 'pgvector' AND mode = 'managed')),
    CHECK (mode = 'managed' OR (embedding_model_id IS NULL AND dimensions IS NULL AND vector_size IS NULL)),
    CHECK (embedding_model_id IS NULL OR vector_size IS NOT NULL)
);

CREATE TABLE rag_config (
    id BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (id),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    reranker_model_id UUID REFERENCES models(id) ON DELETE SET NULL,
    reranker_top_n INTEGER NOT NULL DEFAULT 6 CHECK (reranker_top_n BETWEEN 1 AND 50),
    default_connection_id UUID REFERENCES rag_connections(id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

