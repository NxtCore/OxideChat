-- Per-record access: records of a knowledge base list labels, and these rows say which teams, roles and users hold each label.
-- A label without rows grants nobody.
CREATE TABLE knowledge_base_access_labels (
    knowledge_base_id UUID NOT NULL REFERENCES knowledge_bases(id) ON DELETE CASCADE,
    label TEXT NOT NULL CHECK (char_length(label) BETWEEN 1 AND 200),
    user_id UUID REFERENCES users(id) ON DELETE CASCADE,
    team_id UUID REFERENCES teams(id) ON DELETE CASCADE,
    role_id UUID REFERENCES roles(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (num_nonnulls(user_id, team_id, role_id) = 1),
    UNIQUE NULLS NOT DISTINCT (knowledge_base_id, label, user_id, team_id, role_id)
);

CREATE INDEX idx_knowledge_base_access_labels_user ON knowledge_base_access_labels(user_id) WHERE user_id IS NOT NULL;
CREATE INDEX idx_knowledge_base_access_labels_team ON knowledge_base_access_labels(team_id) WHERE team_id IS NOT NULL;
CREATE INDEX idx_knowledge_base_access_labels_role ON knowledge_base_access_labels(role_id) WHERE role_id IS NOT NULL;

